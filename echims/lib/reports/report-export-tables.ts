import type { ReactNode } from "react";
import { NutritionReportFormat } from "@/lib/reports/export-formats/nutrition-export-format";
import { ProfilingReportFormat } from "@/lib/reports/export-formats/profiling-export-format";
import { VaccinationReportFormat } from "@/lib/reports/export-formats/vaccination-export-format";
import { SupplementationReportFormat } from "@/lib/reports/export-formats/supplementation-export-format";
import { InventoryReportFormat } from "@/lib/reports/export-formats/inventory-export-format";
export type GridCell = {
  text: string;
  header: boolean;
  rowSpan: number;
  colSpan: number;
};
export type ExportTable = { name: string; rows: GridCell[][] };
type Element = { type: unknown; props: Record<string, unknown> };
type Node = {
  tag: string;
  props: Record<string, unknown>;
  children: (Node | string)[];
};
function expand(value: unknown): (Node | string)[] {
  if (value == null || typeof value === "boolean") return [];
  if (typeof value === "string" || typeof value === "number")
    return [String(value)];
  if (Array.isArray(value)) return value.flatMap(expand);
  if (typeof value !== "object" || !("type" in value) || !("props" in value))
    return [];
  const e = value as Element;
  if (typeof e.type === "function") return expand(e.type(e.props));
  if (typeof e.type !== "string") return expand(e.props.children);
  if (["nav", "style", "select", "input", "svg"].includes(e.type)) return [];
  if (
    String(e.props.className ?? "")
      .split(/\s/)
      .includes("nutrition-no-print")
  )
    return [];
  return [{ tag: e.type, props: e.props, children: expand(e.props.children) }];
}
function text(n: Node | string): string {
  return typeof n === "string"
    ? n
    : n.children.map(text).join(" ").replace(/\s+/g, " ").trim();
}
function descendants(n: Node, tag: string): Node[] {
  return n.children.flatMap((c) =>
    typeof c === "string" ? [] : c.tag === tag ? [c] : descendants(c, tag),
  );
}
export type ExportReport = {
  report_id: number;
  title: string;
  module: string;
  period_start: string;
  period_end: string;
  generated_by_name: string;
  generated_at: string;
  validated_by_name: string;
  validated_at: string;
  version: number;
  status: string;
  snapshot: Record<string, unknown>;
};
export function exportTables(report: ExportReport): ExportTable[] {
  const meta = {
    title: report.title,
    generatedBy: report.generated_by_name,
    generatedAt: report.generated_at,
    validatedBy: report.validated_by_name,
    validatedAt: report.validated_at,
    status: report.status,
    version: report.version,
  };
  const snapshot = report.snapshot;
  const plans: { section: string; mode?: string; render: () => ReactNode }[] =
    [];
  const add = <T>(
    fn: (props: T) => ReactNode,
    section: string,
    mode?: string,
  ) =>
    plans.push({
      section,
      mode,
      render: () =>
        fn({ snapshot, meta, exportSection: section, exportMode: mode } as T),
    });
  switch (report.module) {
    case "NUTRITION":
      for (const s of ["Summary", "UW", "SUW", "St", "SSt", "W", "SW"])
        add(NutritionReportFormat, s);
      break;
    case "CHILD":
    case "HOUSEHOLD":
      for (const s of ["SUMMARY", "REGISTER"]) add(ProfilingReportFormat, s);
      break;
    case "VACCINATION":
      for (const m of ["SERVICE", "PRIOR"])
        for (const s of ["SUMMARY", "REGISTER"])
          add(VaccinationReportFormat, s, m);
      break;
    case "SUPPLEMENTATION":
      for (const m of ["ADMINISTERED", "DISPENSED"])
        for (const s of ["SUMMARY", "REGISTER"])
          add(SupplementationReportFormat, s, m);
      add(SupplementationReportFormat, "PLANS", "DISPENSED");
      break;
    case "INVENTORY":
      for (const s of [
        "Monthly inventory",
        "Stock & batches",
        "Movement register",
      ])
        add(InventoryReportFormat, s);
      break;
    default:
      throw new Error("Unsupported report module.");
  }
  const result: ExportTable[] = [
    {
      name: "Report information",
      rows: [
        ["Report ID", report.report_id],
        ["Title", report.title],
        ["Program", report.module],
        ["Period start", report.period_start],
        ["Period end", report.period_end],
        ["Generated by", report.generated_by_name],
        ["Generated at", report.generated_at],
        ["Validated by", report.validated_by_name],
        ["Validated at", report.validated_at],
        ["Version", report.version],
        ["Status", report.status],
      ].map((r) =>
        r.map((v, i) => ({
          text: String(v),
          header: i === 0,
          rowSpan: 1,
          colSpan: 1,
        })),
      ),
    },
  ];
  for (const plan of plans) {
    let count = 0;
    const notes: string[] = [];
    function walk(n: Node | string) {
      if (typeof n === "string") return;
      if (n.tag === "table") {
        const rows = descendants(n, "tr").map((tr) =>
          tr.children
            .filter(
              (c): c is Node =>
                typeof c !== "string" && ["th", "td"].includes(c.tag),
            )
            .map((c) => ({
              text: text(c),
              header: c.tag === "th",
              rowSpan: Number(c.props.rowSpan ?? 1),
              colSpan: Number(c.props.colSpan ?? 1),
            })),
        );
        result.push({
          name: `${plan.mode ?? ""} ${plan.section} ${++count}`.trim(),
          rows,
        });
        return;
      }
      if (n.tag === "button") return;
      if (["p", "h2", "h3", "strong"].includes(n.tag)) {
        const t = text(n);
        if (t) notes.push(t);
        return;
      }
      n.children.forEach(walk);
    }
    expand(plan.render()).forEach(walk);
    if (notes.length)
      result.push({
        name: `${plan.mode ?? ""} ${plan.section} notes`.trim(),
        rows: notes.map((t) => [
          { text: t, header: false, rowSpan: 1, colSpan: 1 },
        ]),
      });
  }
  return result;
}
export type LayoutBlock =
  | { kind: "text"; text: string; className: string; heading: boolean }
  | {
      kind: "table";
      caption?: string;
      captionClass?: string;
      rows: (GridCell & { className: string })[][];
    }
  | { kind: "stack"; children: LayoutBlock[] }
  | { kind: "columns"; children: LayoutBlock[]; columns?: number };
export function exportLayout(
  report: ExportReport,
  section?: string,
  mode?: string,
): LayoutBlock {
  const meta = {
      title: report.title,
      generatedBy: report.generated_by_name,
      generatedAt: report.generated_at,
      validatedBy: report.validated_by_name,
      validatedAt: report.validated_at,
      status: report.status,
      version: report.version,
    },
    snapshot = report.snapshot;
  let tree: ReactNode;
  const props = {
    snapshot,
    meta,
    exportSection: section ?? "SUMMARY",
    exportMode: mode,
  };
  switch (report.module) {
    case "NUTRITION":
      if (
        section &&
        !["Summary", "UW", "SUW", "St", "SSt", "W", "SW"].includes(section)
      )
        throw new Error("Invalid report section.");
      tree = NutritionReportFormat({
        ...props,
        exportSection: section ?? "Summary",
      } as Parameters<typeof NutritionReportFormat>[0]);
      break;
    case "CHILD":
    case "HOUSEHOLD":
      if (section && !["SUMMARY", "REGISTER"].includes(section))
        throw new Error("Invalid report section.");
      tree = ProfilingReportFormat(
        props as Parameters<typeof ProfilingReportFormat>[0],
      );
      break;
    case "VACCINATION":
      if (
        (section && !["SUMMARY", "REGISTER"].includes(section)) ||
        (mode && !["SERVICE", "PRIOR"].includes(mode))
      )
        throw new Error("Invalid report section.");
      tree = VaccinationReportFormat({
        ...props,
        exportMode: mode ?? "SERVICE",
      } as Parameters<typeof VaccinationReportFormat>[0]);
      break;
    case "SUPPLEMENTATION":
      if (
        (section && !["SUMMARY", "REGISTER", "PLANS"].includes(section)) ||
        (mode && !["ADMINISTERED", "DISPENSED"].includes(mode))
      )
        throw new Error("Invalid report section.");
      tree = SupplementationReportFormat({
        ...props,
        exportMode: mode ?? "ADMINISTERED",
      } as Parameters<typeof SupplementationReportFormat>[0]);
      break;
    case "INVENTORY":
      if (
        section &&
        !["Monthly inventory", "Stock & batches", "Movement register"].includes(
          section,
        )
      )
        throw new Error("Invalid report section.");
      tree = InventoryReportFormat({
        ...props,
        exportSection: section ?? "Monthly inventory",
      } as Parameters<typeof InventoryReportFormat>[0]);
      break;
    default:
      throw new Error("Unsupported report module.");
  }
  function block(n: Node | string): LayoutBlock | null {
    if (typeof n === "string")
      return n.trim()
        ? { kind: "text", text: n, className: "", heading: false }
        : null;
    const cls = String(n.props.className ?? "");
    if (n.tag === "button" || cls.includes("sr-only")) return null;
    if (n.tag === "table") {
      const rows: (GridCell & { className: string })[][] = [];
      function collect(node: Node, inherited: string) {
        const classes = inherited + " " + String(node.props.className ?? "");
        if (node.tag === "tr") {
          rows.push(
            node.children
              .filter(
                (c): c is Node =>
                  typeof c !== "string" && ["th", "td"].includes(c.tag),
              )
              .map((c) => ({
                text: text(c),
                header: c.tag === "th",
                rowSpan: Number(c.props.rowSpan ?? 1),
                colSpan: Number(c.props.colSpan ?? 1),
                className: classes + " " + String(c.props.className ?? ""),
              })),
          );
          return;
        }
        node.children.forEach((c) => {
          if (typeof c !== "string") collect(c, classes);
        });
      }
      collect(n, "");
      const caption = n.children.find(
        (c): c is Node =>
          typeof c !== "string" &&
          c.tag === "caption" &&
          !String(c.props.className ?? "").includes("sr-only"),
      );
      return {
        kind: "table",
        rows,
        caption: caption ? text(caption) : undefined,
        captionClass: caption
          ? String(caption.props.className ?? "")
          : undefined,
      };
    }
    if (
      ["p", "h1", "h2", "h3", "h4", "strong"].includes(n.tag) ||
      n.children.every(
        (c) =>
          typeof c === "string" ||
          ["strong", "span", "b", "br"].includes(c.tag),
      )
    )
      return text(n)
        ? {
            kind: "text",
            text: text(n),
            className: cls,
            heading: /^h[1-4]$/.test(n.tag),
          }
        : null;
    const children = n.children
      .map(block)
      .filter((b): b is LayoutBlock => b !== null);
    const cols = cls.match(/(?:^|\s)(?:[\w-]+:)?grid-cols-(\d+)/)?.[1];
    if (cls.includes("grid") && cols)
      return { kind: "columns", columns: Number(cols), children };
    return { kind: "stack", children };
  }
  return {
    kind: "stack",
    children: expand(tree)
      .map(block)
      .filter((b): b is LayoutBlock => b !== null),
  };
}
export function layoutTables(layout: LayoutBlock): ExportTable[] {
  const tables: ExportTable[] = [];
  let title = "Report";
  function walk(b: LayoutBlock) {
    if (b.kind === "text") {
      if (b.heading) title = b.text;
      tables.push({
        name: "",
        rows: [[{ text: b.text, header: b.heading, rowSpan: 1, colSpan: 1 }]],
      });
      return;
    }
    if (b.kind === "table") {
      tables.push({ name: b.caption || title, rows: b.rows });
      return;
    }
    b.children.forEach(walk);
  }
  walk(layout);
  return tables;
}
